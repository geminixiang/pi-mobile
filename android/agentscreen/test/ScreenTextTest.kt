package dev.geminixiang.pimobile

fun main() {
    check(clip("a".repeat(299)) == "a".repeat(299))
    check(clip("a".repeat(301)) == "a".repeat(300) + "…")
    check(clip("  one\n two  ") == "one two")
    check(fieldLabel("", "Email", false) == "empty hint=\"Email\"")
    check(fieldLabel("Email", "Email", false) == "\"Email\" hint=\"Email\"")
    check(fieldLabel("secret", "Password", true) == "hidden hint=\"Password\"")
    val many = ScreenText("settings", false, (1..240).map { "[$it] text \"row $it\"" }, true)
    check(many.more == 80)
    check(many.listed.size == 160)
    check(many.changes(null).first == false)
    check(many.changes(many) == (true to ""))
    val original = ScreenText("settings", false, (1..10).map { "[$it] text \"row $it\"" }, true)
    val changed = original.copy(lines = original.lines.map { if (it.startsWith("[2]")) "[2] text changed" else it })
    check(changed.changes(original) == (true to "[2] text changed"))
    val removed = original.copy(lines = original.lines.dropLast(1))
    check(removed.changes(original) == (true to "gone: [10]"))
    check(original.copy(front = "other").changes(original).first == false)
    check(original.copy(keyboard = true).changes(original).first == false)
    check(original.copy(complete = false).changes(original).first == false)
    check(original.copy(lines = original.lines.take(2)).changes(original).first == false)
    check(original.copy(lines = listOf("# app dialog/modal") + original.lines).changes(original).first == false)
    val events = ScreenChanges()
    events.record(0, 1100L)
    check(events.pending(7, 1000L, 1000L, 1500L, 2500L))
    events.record(0, 1950L)
    check(!events.pending(7, 1000L, 1000L, 2001L, 2500L))
    events.record(7, 1200L)
    check(!events.pending(7, 1000L, 1000L, 1600L, 2500L))
    events.record(7, 1600L)
    check(events.pending(7, 1000L, 1000L, 1700L, 2500L))
    check(!events.pending(7, 1000L, 1000L, 1700L, 500L))
    println("PASS: per-display settle, 300-character labels, field values/hints, hidden passwords, true overflow, changed/gone lines and full-screen fallback")
}
