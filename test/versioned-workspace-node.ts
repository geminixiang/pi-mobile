import assert from "node:assert/strict";
import { indexedDB } from "fake-indexeddb";
import { VersionedWorkspaceStore, WorkspaceConflict } from "../src/experimental/versioned-workspace.ts";

const db = `workspace-test-${crypto.randomUUID()}`;
let a = await VersionedWorkspaceStore.open(db, indexedDB);
const b = await VersionedWorkspaceStore.open(db, indexedDB);
await a.workspace("seed");
await a.write("seed", "/note.md", "base");
const base = await a.commit("seed", "main", "seed");
await a.fork("experiment", base);
await a.workspace("left");
await b.workspace("right");
await a.write("left", "/a.md", "A");
await b.write("right", "/b.md", "B");
await Promise.all([a.commit("left", "main", "left"), b.commit("right", "main", "right")]);
await a.workspace("reader");
assert.equal(await a.read("reader", "/a.md"), "A");
assert.equal(await a.read("reader", "/b.md"), "B");
assert.deepEqual(await a.diff(base, await a.head()), ["/a.md", "/b.md"]);
await a.workspace("conflictA");
await b.workspace("conflictB");
await a.write("conflictA", "/note.md", "first");
await b.write("conflictB", "/note.md", "second");
const first = await a.commit("conflictA", "main", "first");
await assert.rejects(b.commit("conflictB", "main", "second"), WorkspaceConflict);
assert.equal(await b.head(), first);
assert.equal(await b.read("conflictB", "/note.md"), "second");
await a.write("conflictA", "/pending.md", "survives restart");
a.close();
a = await VersionedWorkspaceStore.open(db, indexedDB);
assert.equal(await a.read("conflictA", "/pending.md"), "survives restart");
assert.equal(await a.commit("conflictA", "main", "first"), first);
assert.equal(await a.read("conflictA", "/pending.md"), "survives restart");
await assert.rejects(a.commit("conflictA", "experiment", "first"), /reused/);
await a.workspace("old", "experiment");
assert.equal(await a.read("old", "/note.md"), "base");
assert.equal(await a.read("old", "/a.md"), null);
await a.write("old", "/note.md", null);
await a.commit("old", "experiment", "delete");
assert.equal(await a.read("old", "/note.md"), null);
await assert.rejects(a.write("old", "/../secret", "no"), /canonical/);
await assert.rejects(a.workspace("__proto__"), /Invalid/);
// Identical edits converge; an explicit no-op must not revert a concurrent change.
await a.workspace("sameA"); await b.workspace("sameB");
await a.write("sameA", "/same", "same"); await b.write("sameB", "/same", "same");
await a.commit("sameA", "main", "sameA"); await b.commit("sameB", "main", "sameB");
await a.workspace("noop"); await b.workspace("change");
await a.write("noop", "/note.md", "first");
await b.write("change", "/note.md", "new");
await b.commit("change", "main", "change");
await a.commit("noop", "main", "noop");
assert.equal(await a.read("noop", "/note.md"), "new");
a.close(); b.close();
console.log("Versioned workspace PoC: persistence, concurrent merge, atomic conflict, replay, fork, deletion, validation passed");
