#!/usr/bin/env python3
import os
import subprocess
import tempfile

RES = "android/app/src/main/res"
MAC_ICNS = "host/macos/pi-mobile.icns"
CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
BG = "#161D27"
GRID = "#14FFFFFF"

TOP = [(0, 0, 3, 1), (2, 1, 1, 1)]
LEFT = [(0, 1, 1, 3), (1, 2, 1, 1)]
RIGHT = [(3, 2, 1, 2)]
TOP_COLOR, LEFT_COLOR, RIGHT_COLOR = "#6A9FCC", "#A3A473", "#E1B06E"

UNIT = 11
WIDTH, HEIGHT = 4 * UNIT, 4 * UNIT
OX, OY = (108 - WIDTH) / 2, (108 - HEIGHT) / 2


def rects(cells, ox, oy, unit):
    return "".join(
        f"M{ox + x * unit:g},{oy + y * unit:g}h{w * unit:g}v{h * unit:g}h{-w * unit:g}z" for x, y, w, h in cells
    )


def vector(paths):
    body = "\n".join(f'    <path android:fillColor="{color}" android:pathData="{data}"/>' for color, data in paths)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/make-icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
{body}
</vector>
"""


def notification_icon():
    unit, pad = 5, 2
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/make-icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">
    <path android:fillColor="#FFFFFFFF" android:pathData="{rects(TOP + LEFT + RIGHT, pad, pad, unit)}"/>
</vector>
"""


def grid_path():
    lines = []
    start_x = OX % UNIT
    start_y = OY % UNIT
    x = start_x
    while x <= 108:
        lines.append(f"M{x - 0.15:g},0h0.3v108h-0.3z")
        x += UNIT
    y = start_y
    while y <= 108:
        lines.append(f"M0,{y - 0.15:g}h108v0.3h-108z")
        y += UNIT
    return "".join(lines)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def main():
    glyph = [(TOP_COLOR, rects(TOP, OX, OY, UNIT)), (LEFT_COLOR, rects(LEFT, OX, OY, UNIT)), (RIGHT_COLOR, rects(RIGHT, OX, OY, UNIT))]
    write(f"{RES}/drawable/ic_launcher_foreground.xml", vector(glyph))
    write(f"{RES}/drawable/ic_launcher_background.xml", vector([(BG, "M0,0h108v108h-108z"), (GRID, grid_path())]))
    mono = rects(TOP + LEFT + RIGHT, OX, OY, UNIT)
    write(f"{RES}/drawable/ic_launcher_monochrome.xml", vector([("#FFFFFFFF", mono)]))
    write(f"{RES}/drawable/ic_notification.xml", notification_icon())
    adaptive = """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
"""
    for name in ("ic_launcher", "ic_launcher_round"):
        write(f"{RES}/mipmap-anydpi-v26/{name}.xml", adaptive)

    svg_cells = lambda cells, color: "".join(
        f'<rect x="{OX + x * UNIT:g}" y="{OY + y * UNIT:g}" width="{w * UNIT:g}" height="{h * UNIT:g}" fill="{color}"/>'
        for x, y, w, h in cells
    )
    grid_lines = "".join(
        f'<rect x="{OX % UNIT + i * UNIT - 0.15:g}" y="0" width="0.3" height="108" fill="#fff" fill-opacity="0.08"/>'
        f'<rect x="0" y="{OY % UNIT + i * UNIT - 0.15:g}" width="108" height="0.3" fill="#fff" fill-opacity="0.08"/>'
        for i in range(13)
    )
    svg = (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72" shape-rendering="crispEdges">'
        f'<rect x="0" y="0" width="108" height="108" fill="{BG}"/>{grid_lines}'
        + svg_cells(TOP, TOP_COLOR) + svg_cells(LEFT, LEFT_COLOR) + svg_cells(RIGHT, RIGHT_COLOR)
        + "</svg>"
    )
    sizes = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
    with tempfile.TemporaryDirectory() as tmp:
        for density, size in sizes.items():
            for name, radius in (("ic_launcher", "12%"), ("ic_launcher_round", "50%")):
                html = os.path.join(tmp, "icon.html")
                with open(html, "w") as f:
                    f.write(
                        f'<html><body style="margin:0;background:transparent"><div style="width:{size}px;height:{size}px;'
                        f'border-radius:{radius};overflow:hidden">{svg.replace("<svg ", f"<svg width={size} height={size} ")}</div></body></html>'
                    )
                out = f"{RES}/mipmap-{density}/{name}.png"
                subprocess.run(
                    [CHROME, "--headless=new", "--hide-scrollbars", "--default-background-color=00000000",
                     f"--window-size={size},{size}", f"--screenshot={os.path.abspath(out)}", f"file://{html}"],
                    check=True, capture_output=True,
                )
            stale = f"{RES}/mipmap-{density}/ic_launcher_foreground.png"
            if os.path.exists(stale):
                os.remove(stale)
    write("assets/icon.svg", svg.replace('viewBox="18 18 72 72"', 'viewBox="0 0 108 108"'))


def mac_icon():
    cells = lambda items, color: "".join(
        f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="{color}"/>' for x, y, w, h in items
    )
    unit = 824 * UNIT / 72
    ox = oy = 100 + (824 - 4 * unit) / 2
    place = lambda items: [(ox + x * unit, oy + y * unit, w * unit, h * unit) for x, y, w, h in items]
    grid = "".join(
        f'<rect x="{100 + (ox - 100) % unit + i * unit - 1:g}" y="100" width="2" height="824" fill="#fff" fill-opacity="0.08"/>'
        f'<rect x="100" y="{100 + (oy - 100) % unit + i * unit - 1:g}" width="824" height="2" fill="#fff" fill-opacity="0.08"/>'
        for i in range(int(824 / unit) + 1)
    )
    svg = (
        '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">'
        '<defs><clipPath id="c"><rect x="100" y="100" width="824" height="824" rx="185"/></clipPath></defs>'
        f'<g clip-path="url(#c)"><rect x="100" y="100" width="824" height="824" fill="{BG}"/>{grid}</g>'
        + cells(place(TOP), TOP_COLOR) + cells(place(LEFT), LEFT_COLOR) + cells(place(RIGHT), RIGHT_COLOR)
        + "</svg>"
    )
    with tempfile.TemporaryDirectory() as tmp:
        html = os.path.join(tmp, "icon.html")
        with open(html, "w") as f:
            f.write(f'<html><body style="margin:0;background:transparent">{svg}</body></html>')
        master = os.path.join(tmp, "icon.png")
        subprocess.run(
            [CHROME, "--headless=new", "--hide-scrollbars", "--default-background-color=00000000",
             "--window-size=1024,1024", f"--screenshot={master}", f"file://{html}"],
            check=True, capture_output=True,
        )
        iconset = os.path.join(tmp, "pi-mobile.iconset")
        os.makedirs(iconset)
        for size in (16, 32, 128, 256, 512):
            for scale in (1, 2):
                name = f"icon_{size}x{size}{'@2x' if scale == 2 else ''}.png"
                subprocess.run(["sips", "-z", str(size * scale), str(size * scale), master, "--out", os.path.join(iconset, name)],
                               check=True, capture_output=True)
        os.makedirs(os.path.dirname(MAC_ICNS), exist_ok=True)
        subprocess.run(["iconutil", "-c", "icns", iconset, "-o", MAC_ICNS], check=True)


if __name__ == "__main__":
    main()
    mac_icon()
